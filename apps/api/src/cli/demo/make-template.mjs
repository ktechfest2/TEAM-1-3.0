// Renders the sample poster template (needs system fonts, so run it on a workstation, not in the API image):
//   node apps/api/src/cli/demo/make-template.mjs
// Writes poster-template.ts next to this file. The seed draws figures, codes, stamp and signature on it as shapes.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../../../package.json', import.meta.url));
const sharp = require('sharp');

export const PARTIES = ['AA', 'ADC', 'ADP', 'APC', 'APGA', 'APM', 'APP', 'LP', 'NNPP', 'NRM', 'PDP', 'SDP', 'YPP', 'ZLP'];
const W = 800, H = 1040, ROW0 = 290, ROWH = 40;
const green = '#1f7a3a', ink = '#222';
const rows = PARTIES.map((p, i) => {
  const y = ROW0 + i * ROWH;
  return `<line x1="40" x2="760" y1="${y + ROWH}" y2="${y + ROWH}" stroke="#999" stroke-width="1.5"/>
  <text x="70" y="${y + 27}" font-size="20" text-anchor="middle" fill="${ink}">${i + 1}</text>
  <text x="125" y="${y + 27}" font-size="21" font-weight="700" fill="${ink}">${p}</text>`;
}).join('');
const yEnd = ROW0 + PARTIES.length * ROWH;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" font-family="Helvetica, Arial, sans-serif">
<rect width="${W}" height="${H}" fill="#fbfaf6"/>
<rect x="14" y="14" width="${W - 28}" height="${H - 28}" rx="34" fill="none" stroke="${green}" stroke-width="9"/>
<text x="400" y="78" font-size="30" font-weight="800" text-anchor="middle" fill="${green}">SAMPLE RESULT POSTER</text>
<text x="400" y="112" font-size="19" font-weight="700" text-anchor="middle" fill="#b3261e">TRUSTELECT DEMO DATA · NOT A REAL ELECTION RESULT</text>
<text x="50" y="165" font-size="20" fill="${ink}">ELECTION: <tspan font-weight="700">GOVERNORSHIP</tspan>      STATE: <tspan font-weight="700">EDO</tspan></text>
<text x="50" y="215" font-size="20" fill="${ink}">POLLING UNIT CODE:</text>
<line x1="250" x2="560" y1="222" y2="222" stroke="#777" stroke-dasharray="4 4"/>
<rect x="40" y="250" width="720" height="${yEnd - 250}" fill="none" stroke="${ink}" stroke-width="2"/>
<line x1="100" x2="100" y1="250" y2="${yEnd}" stroke="${ink}" stroke-width="1.5"/>
<line x1="330" x2="330" y1="250" y2="${yEnd}" stroke="${ink}" stroke-width="1.5"/>
<text x="70" y="277" font-size="16" font-weight="700" text-anchor="middle" fill="${ink}">S/N</text>
<text x="125" y="277" font-size="16" font-weight="700" fill="${ink}">PARTY</text>
<text x="350" y="277" font-size="16" font-weight="700" fill="${ink}">VOTES (IN FIGURES)</text>
<line x1="40" x2="760" y1="${ROW0}" y2="${ROW0}" stroke="${ink}" stroke-width="2"/>
${rows}
<text x="50" y="${yEnd + 45}" font-size="19" font-weight="700" fill="${ink}">TOTAL VALID VOTES</text>
<text x="50" y="${yEnd + 95}" font-size="19" font-weight="700" fill="${ink}">REJECTED BALLOTS</text>
<text x="50" y="${yEnd + 155}" font-size="17" fill="${ink}">PRESIDING OFFICER SIGNATURE</text>
<line x1="330" x2="620" y1="${yEnd + 160}" y2="${yEnd + 160}" stroke="#777"/>
</svg>`;
const png = await sharp(Buffer.from(svg)).png({ palette: true, colours: 32, compressionLevel: 9 }).toBuffer();
const out = new URL('./poster-template.ts', import.meta.url);
writeFileSync(out, `// Generated by make-template.mjs: the sample poster without figures (PNG, ${W}x${H}). Do not edit.
export const TEMPLATE = { width: ${W}, height: ${H}, row0: ${ROW0}, rowHeight: ${ROWH}, yEnd: ${yEnd} } as const;
export const TEMPLATE_PARTIES = ${JSON.stringify(PARTIES)} as const;
export const TEMPLATE_PNG_BASE64 =
  '${png.toString('base64')}';
`);
console.log('template', png.length, 'bytes');
